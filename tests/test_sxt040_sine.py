F32 = lambda x: struct.unpack("f", struct.pack("f", x))[0]  # noqa: E731
ONE = 1 << 21


def _mul(a, b):
    return F32(a * b)


def _add(a, b):
    return F32(a + b)


def _sub(a, b):
    return F32(a - b)


def _div(a, b):
    return F32(a / b)


def ref_shape(mode, s, c):
    """float32-emulated transcription of the pinned
    valueFromSinAndCosForMode<mode> (SineOscillator.cpp)."""
    s2x = _mul(2.0, _mul(s, c))
    c2x = _sub(1.0, _mul(2.0, _mul(s, s)))

    def m1(y):
        cc = _sub(1.0, _mul(2.0, _mul(y, y)))
        return _mul(0.5, _sub(1.0, cc)) if y >= 0 else _mul(0.5, _sub(cc, 1.0))

    def m3(y):
        cc = _sub(1.0, _mul(2.0, _mul(y, y)))
        return _mul(0.5, _sub(1.0, cc)) if y >= 0 else 0.0

    def quad(sv, cv):
        sl = 1 if sv <= 0 else 0
        cl = 1 if cv <= 0 else 0
        return 3 * sl + cl - 2 * sl * cl + 1

    if mode == 0:
        return s
    if mode == 1:
        return m1(s)
    if mode == 2:
        return s if s >= 0 else 0.0
    if mode == 3:
        return m3(s)
    if mode == 4:
        return s2x if s >= 0 else 0.0
    if mode == 5:
        return m1(s2x) if s >= 0 else 0.0
    if mode == 6:
        return abs(s2x if s >= 0 else 0.0)
    if mode == 7:
        return abs(m1(s2x) if s >= 0 else 0.0)
    if mode == 8:
        return _sub(_mul(2.0, s if s >= 0 else 0.0), 1.0)
    if mode == 9:
        return s if _mul(s, c) <= 0 else 0.0
    if mode == 10:
        return s if _mul(s, c) >= 0 else 0.0
    if mode == 11:
        return _sub(_mul(2.0, m3(s)), 1.0)
    if mode == 12:
        return _mul(s2x, 1.0 if c >= 0 else -1.0)
    if mode == 13:
        v = _mul(-1.0 if s <= 0 else 1.0, s2x)
        return v if s2x >= 0 else 0.0
    if mode == 14:
        return abs(c2x) if s >= 0 else 0.0
    if mode == 15:
        return (_sub(1.0, s) if s >= 0 else _sub(-1.0, s)) if c >= 0 else 0.0
    if mode == 16:
        return (_sub(1.0, s) if s >= 0 else _sub(c, 1.0)) if c >= 0 else 0.0
    if mode == 17:
        return _sub(1.0 if s >= 0 else -1.0, s)
    if mode == 18:
        return c if c <= 0 else _mul(1.0 if s >= 0 else -1.0, s2x)
    if mode == 19:
        s4x = _mul(2.0, _mul(s2x, c2x))
        return (s2x if c >= 0 else -s4x) if s >= 0 else s
    if mode == 20:
        sbc = _mul(s, c)
        return s if sbc >= 0 else (1.0 if s >= 0 else -1.0)
    if mode == 21:
        sbc = _mul(s, c)
        return (1.0 if s >= 0 else -1.0) if sbc >= 0 else s
    if mode == 22:
        return s if c >= 0 else 0.0
    if mode == 23:
        return s if c <= 0 else 0.0
    if mode == 24:
        return _sub(1.0, s) if s >= 0 else s
    if mode == 25:
        return _div(s2x, float(quad(s, c))) if s >= 0 else 0.0
    if mode == 26:
        return 0.0 if (s <= 0 and c <= 0) else s
    if mode == 27:
        return _div(s2x, float(quad(s, c)))
    if mode == 28:
        sw = 1.0 if s >= 0 else -1.0
        pm = 1.0 if _mul(s, c) < 0 else -1.0
        return _add(sw, _mul(pm, c))
    if mode == 29:
        h1 = s >= 0
        q2 = h1 and c <= 0
        fh = 1.0 if h1 else 0.0
        cx = _mul(_mul(fh, c), _add(-1.0, _mul(2.0, 1.0 if q2 else 0.0)))
        return _add(fh, cx)
    if mode in (30, 31):
        sw = 1.0 if s2x >= 0 else -1.0
        pm = 1.0 if _mul(s2x, c2x) < 0 else -1.0
        v1 = _add(sw, _mul(pm, c2x))
        r = v1 if s >= 0 else 0.0
        return abs(r) if mode == 31 else r
    raise RuntimeError(mode)


def _synth_inputs(tmp, **over):
    """Deterministic declared-class configuration (test configuration; the
    parameter values are drawn from the recovery-basis presets' observed
    ranges — see model/oscillators/sine/README.md)."""
    d = {
        "schema_version": 1, "issue": "SXT-040", "carrier": "test",
        "slot": 0, "preset_path": "test-configuration",
        "preset_census_blob_sha1": "0",
        "octave": -1, "scene_octave": 0, "keytrack": True,
        "pitch_param": 0.0, "pitch_extend": False, "retrigger": True,
        "shape": 8, "fb": 0.0, "fb_extend": False, "fmmode": 1,
        "lowcut": -60.0, "highcut": 70.0, "unison_detune": 0.033928,
        "extend_detune": False, "absolute_detune": False, "unison": 4,
        "character": 0, "drift": 0.0, "o_level": 0.8, "level_pfg": 0.0,
        "pan": 0.0, "scene_volume": 0.9, "vca_db": 3.0,
        "vca_velsense": 0.0, "master_db": -2.0,
        "adsr": {"a": -5.2, "d": -3.0, "s": 0.6, "r": -3.5, "a_s": 1.0,
                 "d_s": 1.0, "r_s": 2.0, "mode": 0.0},
    }
    d.update(over)
    path = os.path.join(tmp, "synth.json")
    with open(path, "w") as f:
        json.dump(d, f)
    return path


def _run_model(inputs, out, seq="seq-notes-repeated-v1", blocks=96,
               env=None):
    e = dict(os.environ)
    if env:
        e.update(env)
    return subprocess.run(
        [sys.executable, os.path.join(SINE, "run_model.py"),
         "--inputs", inputs, "--sequence", seq, "--out-dir", out,
         "--rtl", "--max-blocks", str(blocks)],
        capture_output=True, text=True, env=e, cwd=REPO)


def _compare(run_dir, tb=TB):
    return subprocess.run(
        [sys.executable, os.path.join(REPO, "tools",
                                      "compare_sine_rtl_model.py"),
         "--run-dir", run_dir, "--tb", tb],
        capture_output=True, text=True, cwd=REPO)


