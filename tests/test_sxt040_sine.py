def test_shape_transcription_matches_pinned_sse_semantics():
    # all 32 modes vs a float32-emulated model of valueFromSinAndCosForMode;
    # points off the sub-LSB sign boundary (a declared deviation) and off
    # the |s|,|c| ~ 1e-3 product-underflow corner (unreachable from
    # sin/cos pairs on the unit circle - both |s|,|c| tiny cannot occur)
    import random
    rng = random.Random(11)
    lsb = 1.0 / ONE
    pts = [(rng.uniform(-1, 1), rng.uniform(-1, 1)) for _ in range(4000)]
    for _ in range(800):
        s = rng.choice([rng.uniform(2 * lsb, 1), rng.uniform(-1, -2 * lsb),
                        0.0])
        c = rng.choice([rng.uniform(2 * lsb, 1), rng.uniform(-1, -2 * lsb),
                        0.0])
        pts.append((s, c))
    for mode in range(32):
        for s, c in pts:
            want = ref_shape(mode, s, c)
            got = sm.shape_out(mode, vm.qint(s), vm.qint(c)) / ONE
            assert abs(got - want) <= 30e-6 * max(1.0, abs(want)), \
                (mode, s, c, want, got)


def test_mode27_quadrant_divide_is_integer_scaled():
    # the quadrant divisor is a plain integer 1..4 (fb=0 in vm.qdiv), not a
    # Q10.21 word - regression guard for the 2^21 scaling bug
    s = vm.qint(0.5)
    c = vm.qint(0.5)
    s2x = 2 * ((s * c + (1 << 20)) >> 21)   # the model's shl1(qmul(s, c))
    got = sm.shape_out(27, s, c)
    want = vm.qdiv(s2x, 1, fb=0)  # quadrant(s>0, c>0) = 1
    assert got == want
    got25 = sm.shape_out(25, s, c)
    assert got25 == want


def test_pitch_param_extend_semantics():
    # Mystery 4: pitch_param 1.075 with extend_range FALSE = +1.075 st
    d = json.loads(open(os.path.join(SINE, "inputs", "mystery4.json")).read()
                   ) if os.path.exists(os.path.join(
                       SINE, "inputs", "mystery4.json")) else None
    assert d is None or (d["pitch_extend"] is False
                         and abs(d["pitch_param"] - 1.0750559568405151) < 1e-6)
    import tempfile
    with tempfile.TemporaryDirectory() as tmp:
        i = sm.Inputs(_synth_inputs(tmp, pitch_param=1.075,
                                    pitch_extend=False,
                                    octave=-1, scene_octave=-1))
        o = sm.SineOsc(i, 60)
        assert abs(o.pitch - (60 - 24 + 1.075)) < 1e-9
        i2 = sm.Inputs(_synth_inputs(tmp, pitch_param=1.075,
                                     pitch_extend=True,
                                     octave=-1, scene_octave=-1))
        o2 = sm.SineOsc(i2, 60)
        assert abs(o2.pitch - (60 - 24 + 12.9)) < 1e-6


def test_unison_constants_match_unisonsetup():
    with tempfile.TemporaryDirectory() as tmp:
        inp = sm.Inputs(_synth_inputs(tmp, unison=6, unison_detune=0.2))
        o = sm.SineOsc(inp, 48)
        att = o.out_attenuation / float(ONE)
        assert abs(att - 1.0 / (6 ** 0.5)) < 1e-6
        dets = [round(v, 6) for v in o.voice_detune]
        assert dets == [round(0.2 * (2.0 / 5 * v - 1.0), 6) for v in range(6)]


def test_unison_pan_is_mono_inert():
    # UnisonSetup linear pan law: (panL + panR)/2 = 1 for every voice, so
    # the mono fold cancels it structurally (sum of weights = n)
    with tempfile.TemporaryDirectory() as tmp:
        for uni in (2, 3, 9):
            inp = sm.Inputs(_synth_inputs(tmp, unison=uni))
            osc = sm.SineOsc(inp, 60)
            # every voice contributes with weight exactly 1 to the mono bus
            assert osc.out_attenuation == vm.qint(F32(1.0 / F32(
                math.sqrt(1.0 * uni))))


def test_refusals_are_fail_closed(tmp_path):
    cases = (
        ({"unison": 17}, "unison"),
        ({"absolute_detune": True}, "absolute"),
        ({"drift": 0.3}, "drift"),
        ({"character": 2}, "Bright"),
        ({"shape": 32}, "shape"),
        ({"shape": -1}, "shape"),
        ({"fmmode": 2}, "behavior"),
        ({"adsr": {"a": -5.2, "d": -3.0, "s": 0.6, "r": -3.5, "a_s": 1.0,
                   "d_s": 3.0, "r_s": 2.0, "mode": 0.0}}, "decay shape"),
        ({"adsr": {"a": -5.2, "d": -3.0, "s": 0.6, "r": -3.5, "a_s": 3.0,
                   "d_s": 1.0, "r_s": 2.0, "mode": 0.0}}, "attack shape"),
    )
    for over, msg in cases:
        d = json.loads(open(_synth_inputs(tmp_path)).read())
        d.update(over)
        p = os.path.join(tmp_path, "m.json")
        json.dump(d, open(p, "w"))
        i = sm.Inputs(p)
        if "adsr" in over:
            with pytest.raises(RuntimeError, match=msg):
                sm.AdsrSine(i.adsr, "aeg")
        else:
            with pytest.raises(RuntimeError, match=msg):
                sm.SineOsc(i, 60)


def test_inputs_are_census_pinned_and_retriggered():
    for name in INPUTS:
        d = json.loads(open(os.path.join(SINE, "inputs", name)).read())
        assert d["preset_census_blob_sha1"] != "0", name
        assert d["retrigger"] is True, name
        assert d["drift"] == 0.0, name
        assert 1 <= d["unison"] <= 16, name
        assert not d["absolute_detune"], name
        assert d["fmmode"] in (0, 1), name
        assert 0 <= d["shape"] <= 31, name
        # every committed carrier input must carry the route override and
        # read back route_slot == 1 (the serial-1 A path)
        overrides = dict(d["declared_overrides"])
        assert ("route_slot_1", True) in [(k, v) for k, v in
                                          d["declared_overrides"]], name


