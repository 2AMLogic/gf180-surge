def test_out_of_class_presets_refused():
    # all four refusal controls refuse at the committed-graphs level (no
    # oracle needed): playmode (mortsnare, arp2) and live voice routes
    # (alone, mystery4)
    for carrier, msg in (
            ("mortsnare", "playmode"),
            ("arp2", "playmode"),
            ("alone", "Amp EG Attack"),
            ("mystery4", "Amp EG Attack")):
        r = subprocess.run(
            [sys.executable, os.path.join(SINE, "extract_inputs.py"),
             "--carrier", carrier,
             "--out", os.path.join(tempfile.gettempdir(), carrier + ".json")],
            capture_output=True, text=True, cwd=REPO)
        combined = r.stdout + r.stderr
        if "ORACLE_SURGE_DIR" in combined:
            pytest.skip("external pinned oracle not present")
        assert r.returncode == 2, (carrier, combined)
