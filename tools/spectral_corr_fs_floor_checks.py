def _kt_runner_fields(ref_path, model_path):
    """Fields tools/kt_negative_controls.py adds to the comparator JSON after
    the comparator runs (SXT-042). Recomputed with the runner's own helper on
    the SAME render, so they are proven independent of the metric change."""
    import kt_negative_controls as kt
    return {"windowed_rms_lsb": kt.windowed_rms(kt.read_i16(ref_path),
                                                kt.read_i16(model_path))}


# artifact prefix -> recompute of the fields its runner adds on top of the
# comparator output (absent from the comparator's own JSON by construction)
RUNNER_ADDED = {"reports/SXT-042/artifacts/audio-nc-": _kt_runner_fields}


def _runner_added_check(art, ref_path, model_path, bad):
    """Split `bad` into runner-added keys proven equal on recompute and the
    rest. Returns (still_bad, proven_keys)."""
    fn = next((f for p, f in RUNNER_ADDED.items() if art.startswith(p)), None)
    if fn is None:
        return bad, []
    want = stg.flat(fn(ref_path, model_path))
    still, proven = [], []
    for k, a, b in bad:
        w = want.get(k, "<absent>")
        if a == "<absent>" and isinstance(w, float) and isinstance(b, float) \
                and abs(w - b) <= 1e-12 * max(abs(w), abs(b), 1.0):
            proven.append(k)
        else:
            still.append((k, a, b))
    return still, proven


