def read_mono(path):
    """int16 mono -> (samples, full_scale); stereo f32 -> (mono sum, 1.0)."""
    if tgc._is_mono16(path):
        a, _ = car.read_wav(path)
        return a, car.FULL_SCALE_INT16
    st = stg.read_f32(path).astype(np.float64)
    return 0.5 * (st[0] + st[1]), car.FULL_SCALE_F32


