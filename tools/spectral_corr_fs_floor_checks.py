# Repo-relative modules the comparator imports by path (main's
# compare_audio_reference.py puts <repo>/oracle on sys.path for
# oracle_common); materialized alongside it so the base tool runs as it would
# in a checkout of that revision. Absent at a revision -> not materialized.
_MATERIALIZE_DEPS = ("oracle/oracle_common.py",)


def _materialize(rev, rel, scratch, name):
    src = git_show(rev, rel)
    if src is None:
        return None
    root = os.path.join(scratch, "pre110")
    d = os.path.join(root, "tools")
    os.makedirs(d, exist_ok=True)
    p = os.path.join(d, name)
    with open(p, "wb") as f:
        f.write(src)
    for dep in _MATERIALIZE_DEPS:
        dsrc = git_show(rev, dep)
        if dsrc is not None:
            dp = os.path.join(root, dep)
            os.makedirs(os.path.dirname(dp), exist_ok=True)
            with open(dp, "wb") as f:
                f.write(dsrc)
    return p


def owned_diff(base, cur):
    """Keys that differ outside the fields #110 owns (flat dict compare)."""
    fb, fc = stg.flat(base), stg.flat(cur)
    spectral_moved = any(
        k.endswith("proposed_budget_results/spectral_corr")
        and fb.get(k) != fc.get(k) for k in set(fb) | set(fc))
    bad, owned = [], []
    for k in sorted(set(fb) | set(fc)):
        a, b = fb.get(k, "<absent>"), fc.get(k, "<absent>")
        if a == b:
            continue
        leaf = k.rsplit("/", 1)[-1]
        if leaf in OWNED or k.endswith("proposed_budget_results/spectral_corr"):
            owned.append(k)
        elif leaf == "verdict" and spectral_moved:
            owned.append(k)
        else:
            bad.append((k, a, b))
    return owned, bad


def leg3(lines, scratch):
    emit(lines, "=" * 74)
    emit(lines, "[3] dry re-run parity: pre-#110 comparator (main at base %s) "
                "vs working tree" % BASE_REV[:12])
    emit(lines, "=" * 74)
    base_tool = _materialize(BASE_REV, "tools/compare_audio_reference.py",
                             scratch, "compare_audio_reference.py")
    if base_tool is None:
        emit(lines, "  NOT_RUN: pre-#110 tool not available in this clone")
        return False, {"status": "NOT_RUN", "reason": "rev missing"}
    cases, skipped = tgc.discover_dry_cases()
    ok = True
    rows = []
    for leaf, ref, model in cases:
        bj = os.path.join(scratch, "b.json")
        cj = os.path.join(scratch, "c.json")
        rb = tgc.run_tool(base_tool, ref, model, bj)
        rc = tgc.run_tool(tgc.TOOL, ref, model, cj)
        base = json.load(open(bj))
        cur = json.load(open(cj))
        owned, bad = owned_diff(base, cur)
        good = not bad and rb.returncode == rc.returncode
        ok &= good
        rows.append({"leaf": leaf, "ref": os.path.relpath(ref, REPO),
                     "model": os.path.relpath(model, REPO),
                     "owned_diffs": owned,
                     "unexplained": [list(x) for x in bad],
                     "legacy_spectral_corr": base["spectral_corr"],
                     "adopted_spectral_corr": cur["spectral_corr"],
                     "verdict_before": stg.status_of(base["verdict"]),
                     "verdict_after": stg.status_of(cur["verdict"]),
                     "ok": good})
        emit(lines, "  %-10s %-48s %.4f -> %.4f  %s -> %s  %s"
             % (leaf, os.path.basename(ref)[:48], base["spectral_corr"],
                cur["spectral_corr"], stg.status_of(base["verdict"]),
                stg.status_of(cur["verdict"]),
                "OK (only #110 fields differ)" if good
                else "UNEXPLAINED %r" % bad[:3]))
    for leaf, p, why in skipped:
        emit(lines, "  %-10s %-48s NOT_RUN (%s)"
             % (leaf, os.path.basename(p)[:48], why))
    emit(lines, "  leg 3: %s (%d/%d dry cases differ only in #110-owned "
                "fields)" % ("PASS" if ok else "FAIL",
                             sum(1 for r in rows if r["ok"]), len(rows)))
    emit(lines)
    return ok, {"status": "PASS" if ok else "FAIL",
                "base_rev": BASE_REV, "cases": rows,
                "not_run": [{"leaf": a, "render": os.path.relpath(b, REPO),
                             "reason": c} for a, b, c in skipped]}


