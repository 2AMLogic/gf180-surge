def leg1(lines, scratch):
    emit(lines, "=" * 74)
    emit(lines, "[1] unit invariance / sensitivity sweep (legacy log1p vs "
                "adopted fs-log-floor)")
    emit(lines, "=" * 74)
    emit(lines, "  perturbation: deterministic ternary {-1,0,+1} x k native "
                "LSB everywhere (the #100 pattern)")
    emit(lines, "  native LSB: int16 = 1/32767 FS; f32 = 2^-21 (Q10.21)")
    emit(lines)
    rows = []
    for label, path, ks in SWEEP_FIXTURES:
        ref, fs = read_mono(path)
        unit = 1.0 if fs == car.FULL_SCALE_INT16 else 2.0 ** -21
        pat = stg.pattern(len(ref)).astype(np.float64)
        emit(lines, "  %s: %s" % (label, os.path.relpath(path, REPO)))
        for k in ks:
            mod = ref + pat * k * unit
            d = mod - ref
            r = float(np.sqrt((d * d).mean()))
            row = {"fixture": os.path.relpath(path, REPO), "k_lsb": k,
                   "rms_diff_dbfs": car.rms_dbfs(r, fs),
                   "legacy_native_log1p":
                       car.spectral_corr_legacy_log1p(ref, mod),
                   "adopted": car.spectral_corr(ref, mod, full_scale=fs)}
            rows.append(row)
            emit(lines, "    k=%-6d residual %8.2f dBFS | legacy %.4f %s| "
                        "adopted %.4f %s"
                 % (k, row["rms_diff_dbfs"], row["legacy_native_log1p"],
                    "MISS " if row["legacy_native_log1p"] < BUDGET else "     ",
                    row["adopted"], "MISS" if row["adopted"] < BUDGET else ""))
        emit(lines)
    # unit invariance on real data: the int16 fixture expressed in float FS
    ref, _ = read_mono(SWEEP_FIXTURES[1][1])
    mod = ref + stg.pattern(len(ref)).astype(np.float64)
    inv_i = car.spectral_corr(ref, mod, full_scale=car.FULL_SCALE_INT16)
    inv_f = car.spectral_corr(ref / 32767.0, mod / 32767.0,
                              full_scale=car.FULL_SCALE_F32)
    leg_i = car.spectral_corr_legacy_log1p(ref, mod)
    leg_f = car.spectral_corr_legacy_log1p(ref / 32767.0, mod / 32767.0)
    inv_ok = abs(inv_i - inv_f) < 1e-9
    emit(lines, "  unit invariance, behemoth +-1 LSB expressed on both buses:")
    emit(lines, "    adopted: int16 %.6f | float %.6f -> %s"
         % (inv_i, inv_f, "EQUAL" if inv_ok else "DIFFER"))
    emit(lines, "    legacy : int16 %.6f | float %.6f (unit-bound; the #110 "
                "finding)" % (leg_i, leg_f))
    gated = stg.corr_variant(ref, mod, 32767.0, "gated")
    emit(lines, "  frame gating alone (legacy metric, ref frame >= -80 dBFS) "
                "on behemoth +-1 LSB: %.4f (%s 0.98: gating does not fix the "
                "empty-bin case)" % (gated, "<" if gated < BUDGET else ">="))
    emit(lines)
    ok = inv_ok
    return ok, {"status": "PASS" if ok else "FAIL", "sweep": rows,
                "unit_invariance": {"adopted_int16": inv_i,
                                    "adopted_float": inv_f,
                                    "legacy_int16": leg_i,
                                    "legacy_float": leg_f},
                "frame_gating_alone_behemoth_1lsb": gated}


