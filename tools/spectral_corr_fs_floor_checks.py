def committed_pairs():
    cases, skipped = tgc.discover_dry_cases()
    pairs = [(leaf, os.path.relpath(r, REPO), os.path.relpath(m, REPO))
             for leaf, r, m in cases]
    return pairs + [p for p in STEREO_PAIRS
                    if os.path.exists(os.path.join(REPO, p[1]))
                    and os.path.exists(os.path.join(REPO, p[2]))], skipped


def leg2(lines, scratch):
    emit(lines, "=" * 74)
    emit(lines, "[2] floor sensitivity on every committed model-vs-reference "
                "pair (spectral leg >= %.2f)" % BUDGET)
    emit(lines, "=" * 74)
    emit(lines, "  columns: legacy log1p | adopted at floor " +
         " / ".join("%d" % f for f in FLOORS) + " dBFS per bin")
    emit(lines, "  '*' marks a pair whose spectral-leg outcome differs "
                "anywhere in [-110, -90] dBFS")
    emit(lines)
    pairs, skipped = committed_pairs()
    rows = []
    for leaf, rp, mp in pairs:
        ref, fs = read_mono(os.path.join(REPO, rp))
        mod, fs2 = read_mono(os.path.join(REPO, mp))
        assert fs == fs2, (rp, mp)
        n = min(len(ref), len(mod))
        ref, mod = ref[:n], mod[:n]
        legacy = car.spectral_corr_legacy_log1p(ref, mod)
        at = {f: car.spectral_corr(ref, mod, full_scale=fs, floor_db=f)
              for f in FLOORS}
        near = {at[f] >= BUDGET for f in (-110.0, -100.0, -90.0)}
        sensitive = len(near) > 1
        row = {"leaf": leaf, "ref": rp, "model": mp,
               "full_scale": fs, "legacy": legacy,
               "adopted_by_floor": {"%d" % f: v for f, v in at.items()},
               "legacy_leg_pass": legacy >= BUDGET,
               "adopted_leg_pass": at[-100.0] >= BUDGET,
               "floor_sensitive_90_110": sensitive}
        rows.append(row)
        emit(lines, "  %-12s %-50s %.4f | %s %s"
             % (leaf, os.path.basename(mp)[:50], legacy,
                " ".join("%.4f" % at[f] for f in FLOORS),
                "*" if sensitive else ""))
    for leaf, p, why in skipped:
        emit(lines, "  %-12s %-50s NOT_RUN (%s)"
             % (leaf, os.path.basename(p)[:50], why))
    flips = [r for r in rows if r["legacy_leg_pass"] != r["adopted_leg_pass"]]
    sens = [r for r in rows if r["floor_sensitive_90_110"]]
    emit(lines)
    emit(lines, "  pairs graded: %d; spectral-leg outcome moved legacy -> "
                "adopted: %d; floor-sensitive in [-110,-90]: %d"
         % (len(rows), len(flips), len(sens)))
    for r in flips:
        emit(lines, "    moved: %-10s %s  %s -> %s"
             % (r["leaf"], os.path.basename(r["model"]),
                "PASS" if r["legacy_leg_pass"] else "FAIL",
                "PASS" if r["adopted_leg_pass"] else "FAIL"))
    for r in sens:
        emit(lines, "    floor-sensitive: %-10s %s"
             % (r["leaf"], os.path.basename(r["model"])))
    emit(lines)
    return True, {"status": "PASS", "note": "characterization",
                  "floors_dbfs": list(FLOORS), "rows": rows,
                  "not_run": [{"leaf": a, "render": os.path.relpath(b, REPO),
                               "reason": c} for a, b, c in skipped]}


