#!/usr/bin/env python3
"""Issue #110 checks: the shared full-scale log-floor `spectral_corr`
definition (tools/compare_audio_reference.py SPECTRAL_CORR_*), adopted as a
visible [PROPOSED-TO-BE-FROZEN-AT-PILOT] contract revision and input to the
SXT-017 pilot freeze (#12).

Legs
----
[1] Unit invariance and sensitivity sweep. The #100 perturbation (a
    deterministic ternary +-k native-LSB pattern) on the same four committed
    fixtures (two int16, two stereo float32 mono sums). Reported per row: the
    retired native-unit log1p value, the adopted value, and the residual in
    dBFS. The adopted value depends on the residual level only, not on the
    bus unit. Also records the frame-gating-alone candidate on behemoth (the
    empty-bin case frame gating does not fix).

[2] Floor sensitivity on every committed model-vs-reference pair whose both
    renders are committed (dry int16 pairs discovered by the #93 convention,
    plus the stereo float32 effect-slice pairs). For floors -80 .. -120 dBFS
    per bin, the spectral leg (>= 0.98) is recomputed, so a reviewer can see
    which spectral-leg outcomes depend on the declared -100 dB value. The
    floor was declared in #100 before any case was re-graded; this leg does
    not choose it.

[3] Dry re-run parity against the pre-#110 tool. Every committed dry pair is
    graded by the pre-#110 comparator -- main's, materialized from the BASE
    revision (main as this branch last merged it; see --base-rev) -- and by
    the working tree. The two outputs must be identical except for the fields
    #110 owns: `spectral_corr`, `spectral_corr_definition` (added),
    `proposed_budget_results.spectral_corr`, and `verdict` when (and only
    when) the spectral flag moved. Anything else is UNEXPLAINED and fails the
    leg.

[4] Re-render proof. Negative-control artifacts whose model render is not
    committed were regenerated by re-running their leaf's own runner, which
    re-renders the control model in scratch. For each such render the
    pre-#110 comparator is run on the SAME render: its non-spectral fields
    must equal the regenerated artifact's (so any non-spectral diff against
    the committed artifact comes from the re-render -- the current model on
    this host -- and not from #110). Renders are looked up under
    --renders-root; missing renders make that row NOT_RUN, never a pass.

[5] Tail-gate control legs of #93 (tools/tail_gate_checks.py leg 2) and #100
    (tools/stereo_tail_gate_checks.py leg 2) re-run under the #110 metric;
    their per-control JSONs and transcripts are regenerated and their
    checks-summary.json leg entry is replaced. Every other leg and every
    top-level field is carried byte-identical from the BASE revision's record
    (main's, not an older pinned SHA -- the PR #166 re-review finding), and
    the leg FAILS if the written summary's carried fields differ from it.

[6] Regrade ledger (tools/regrade_spectral_corr.py).

Claim scope: comparator/metric behaviour only. No model-vs-reference fidelity,
RTL, preset-support, or sound claim follows; no budget is frozen here.

Usage:
  python3 tools/spectral_corr_fs_floor_checks.py [--legs 1,2,3,4,5,6]
      [--scratch-root DIR] [--renders-root DIR] [--base-rev REV]
      [--main-ref REF]

The base revision defaults to the merge base of HEAD with origin/main and
is resolved once per run (tools/regrade_spectral_corr.resolve_base_rev),
recorded in checks-summary.json, and passed to the ledger (leg 6).
"""

