#!/usr/bin/env python3
"""Issue #110 regrade ledger: every committed artifact touched by the shared
`spectral_corr` definition change, with its re-run diff and attribution.

The metric change itself lives in tools/compare_audio_reference.py
(`spectral_corr`, SPECTRAL_CORR_*). The committed artifacts are regenerated by
re-running their OWN producing tools (the runner per report is listed in
reports/spectral-corr-fs-floor/EVIDENCE.md); this script rewrites no
artifact. It compares each committed JSON at the base revision
(`--base-rev`) with the working tree and classifies every changed leaf.

The base is `main` as this branch last absorbed it: by default the merge
base of HEAD with `--main-ref` (origin/main), resolved at run time and
recorded in the ledger -- never a hard-coded SHA. So every diff the ledger
walks is this branch's own change against the main it will merge into, and
a leaf this branch put BACK to some older value is a diff like any other
(it differs from the base) and must classify, or it is UNEXPLAINED. (Before
2026-09-30 the ledger diffed against a pinned pre-#110 SHA and skipped every
leaf equal to it, so a revert of main's later history to that SHA was
invisible -- the PR #166 re-review finding.)

  SPECTRAL        a `spectral_corr` value (the intended change)
  BUDGET-#110     the boolean result of the spectral_corr >= budget leg
  RMS-FLAG-#95    proposed_budget_results.rms_diff_dbfs moved to the value the
                  corrected (#92) predicate gives on the artifact's own numbers
                  -- a pre-#92 artifact re-emitted by the current tool (#95
                  audit, #97 re-grade); not caused by #110
  VERDICT         a verdict / status / control-ok field; every STATUS change
                  is listed as a flip with its attributed cause
  DEFINITION      the new `spectral_corr_definition` stamp
  ULP             float equal to 1e-12 relative (host float ordering)
  HOST-PATH       a path string that differs only in the host/worktree/scratch
                  prefix
  RE-RENDER       a non-spectral metric of a negative-control artifact whose
                  model render was re-rendered by its leaf runner (the current
                  model on this host); leg 4 of the #110 checks runs the
                  pre-#110 comparator on the same render to show the diff is
                  the render's, not the metric's
  SCHEMA-#100     a key the #100 wet-path tail gate emits, ADDED (absent at
                  the base) to a pre-#100 sxt-023 record that is now
                  re-emitted by the gated tool
  SCHEMA-#111     a #111 tail-shape (windowed decay-curve) key --
                  `tail_decay_curve`/`decay_curve_*`/`tail_rms_rel_ok`/
                  `tail_decay_curve_ok` -- ADDED (absent at the base) to a
                  record re-emitted by the current tool. Additions only: a
                  #111 key that exists at the base and CHANGED value is not
                  a schema difference, it falls through to VERDICT/OTHER like
                  any other change, so the class cannot launder a moved
                  `tail_rms_rel_ok` or a control-row status.
  RUN-METADATA    run stamps and the partial-re-run note of a merged summary
  OTHER           anything else -- UNEXPLAINED, fails this script

It also lists every JSON under reports/ that still carries a `spectral_corr`
value and was NOT regenerated, with the reason class, so nothing is silently
left graded under the retired definition.

Exit status: 0 when no artifact has an UNEXPLAINED diff, 1 otherwise.
"""

import argparse
import glob
import json
import os
import re
import subprocess
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(REPO, "tools"))
MAIN_REF = "origin/main"


def resolve_base_rev(explicit=None, main_ref=MAIN_REF):
    """The revision this branch's changes are attributed against: `explicit`
    if given, else the merge base of HEAD with `main_ref` -- main as this
    branch last absorbed it. Fails loudly (SystemExit) rather than guessing:
    an unresolvable ref, a base that is not an ancestor of HEAD, or a base
    equal to HEAD (nothing to attribute -- e.g. after this branch merged)."""
    def git(*a):
        return subprocess.run(["git"] + list(a), cwd=REPO,
                              capture_output=True, text=True)
    head = git("rev-parse", "HEAD").stdout.strip()
    if explicit:
        r = git("rev-parse", "--verify", explicit + "^{commit}")
        if r.returncode != 0:
            raise SystemExit("base rev %r does not resolve in this clone"
                             % explicit)
        base = r.stdout.strip()
    else:
        r = git("merge-base", "HEAD", main_ref)
        if r.returncode != 0 or not r.stdout.strip():
            raise SystemExit(
                "cannot derive the base: no merge base of HEAD with %r in "
                "this clone (fetch it, or pass --base-rev explicitly)"
                % main_ref)
        base = r.stdout.strip()
    if git("merge-base", "--is-ancestor", base, "HEAD").returncode != 0:
        raise SystemExit("base %s is not an ancestor of HEAD %s"
                         % (base[:12], head[:12]))
    if base == head:
        raise SystemExit("base %s equals HEAD: nothing to attribute (pass "
                         "--base-rev for the main this branch merged into)"
                         % base[:12])
    return base

