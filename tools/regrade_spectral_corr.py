VERDICT_KEYS = re.compile(r"(^|/)(verdict|status|ok|all_pass|pass|fail|"
                          r"overall|overall_ok|detected|good|control_ok|"
                          r"result|observed)$")


def git_show(rev, path):
    r = subprocess.run(["git", "show", "%s:%s" % (rev, path)], cwd=REPO,
                       capture_output=True)
    return r.stdout.decode() if r.returncode == 0 else None


def leaves(obj, path=""):
    out = {}
    if isinstance(obj, dict):
        for k, v in obj.items():
            out.update(leaves(v, "%s/%s" % (path, k)))
    elif isinstance(obj, list):
        # A list of dict rows carrying a stable "control" name (the #93/#100/
        # #111 controls-list shape) is keyed by that name, not position: #111
        # inserted three new late-tail controls mid-list, and plain positional
        # indexing would misalign every control after the insertion point
        # against a pre-#111 baseline. Duplicate names (e.g. two
        # "refusal/missing-sidecar" rows) are disambiguated by occurrence
        # order, which #111 did not reorder.
        if obj and all(isinstance(x, dict) and "control" in x for x in obj):
            seen = {}
            for v in obj:
                name = v["control"]
                seen[name] = seen.get(name, 0) + 1
                idx = name if seen[name] == 1 else "%s#%d" % (name, seen[name])
                out.update(leaves(v, "%s[%s]" % (path, idx)))
        else:
            for i, v in enumerate(obj):
                out.update(leaves(v, "%s[%d]" % (path, i)))
    else:
        out[path] = obj
    return out


def has_spectral_value(obj):
    return any(k.rsplit("/", 1)[-1] == "spectral_corr"
               and isinstance(v, float) for k, v in leaves(obj).items())


def status_of(v):
    if isinstance(v, bool):
        return v
    if not isinstance(v, str):
        return v
    for s in ("NO_VERDICT", "PASS", "FAIL", "NOT_RUN", "BLOCKED", "STALE",
              "CONTROL-OK", "CONTROL-BROKEN"):
        if v.upper().startswith(s):
            return s
    return v


def _norm_path(s):
    # the checkout this run executes in is a host prefix like any other; strip
    # it first, or a checkout that itself lives under /tmp would have its
    # repo-relative tail swallowed by the scratch rule below
    s = s.replace(REPO + "/", "")
    return re.sub(r"[^ ]*/(reports|fixtures|tools|model)/", r"\1/",
                  re.sub(r"/(private/)?tmp/[^ ;]*?/(?=[^/ ]+( |$|;|\)))",
                         "/tmp/<scratch>/", s))


def classify(rel, key, old, new, flat_new):
    last = key.rsplit("/", 1)[-1]
    if last == "spectral_corr_definition":
        return "DEFINITION"
    if METADATA_KEYS.search(key):
        return "RUN-METADATA"
    if key.endswith("proposed_budget_results/spectral_corr") or \
            key.endswith("budget_results/spectral_corr") or \
            re.search(r"spectral_corr>=", key):
        return "BUDGET-#110"
    if key.endswith("proposed_budget_results/rms_diff_dbfs"):
        base = key[: -len("proposed_budget_results/rms_diff_dbfs")]
        val = flat_new.get(base + "rms_diff_dbfs")
        bud = flat_new.get(base + "proposed_budgets/rms_diff_dbfs")
        if isinstance(val, float) and isinstance(bud, (int, float)) and \
                new == (val <= bud):
            return "RMS-FLAG-#95"
    # Schema classes are ADDITIONS only (the key is absent at the base): a
    # re-emitted record gaining the fields a newer tool writes. A key that
    # exists at the base and changed value is never a schema difference --
    # it must classify on its own merits below (VERDICT, SPECTRAL, ...) or be
    # UNEXPLAINED.
    if old == "<absent>" and SCHEMA100_ARTIFACTS.search(rel) and \
            SCHEMA100_KEYS.search(key):
        return "SCHEMA-#100"
    if old == "<absent>" and SCHEMA111_KEYS.search(key):
        return "SCHEMA-#111"
    if VERDICT_KEYS.search(key) or last.startswith("verdict") or \
            re.search(r"beyond_model_error_via", key):
        return "VERDICT"
    if last == "spectral_corr":
        return "SPECTRAL"
    if isinstance(old, float) and isinstance(new, float) and \
            abs(old - new) <= 1e-12 * max(abs(old), abs(new)):
        return "ULP"
    if isinstance(old, str) and isinstance(new, str) and \
            _norm_path(old) == _norm_path(new):
        return "HOST-PATH"
    if RERENDER_ARTIFACTS.search(rel):
        return "RE-RENDER"
    return "OTHER"


def cause_of_flip(changes, lo, ln):
    """Attribute a verdict flip. For the shared comparator's flat shape the
    decisive leg is checked by counterfactual: the new flags with the OLD
    spectral flag must give the old status for #110 to be decisive."""
    pb = "/proposed_budget_results/"
    if pb + "spectral_corr" in lo and pb + "spectral_corr" in ln:
        flags = {k: v for k, v in ln.items() if k.startswith(pb)}
        cf = dict(flags)
        cf[pb + "spectral_corr"] = lo[pb + "spectral_corr"]
        new_ok, cf_ok = all(flags.values()), all(cf.values())
        rms_moved = lo.get(pb + "rms_diff_dbfs") != ln.get(pb + "rms_diff_dbfs")
        if new_ok != cf_ok:
            return ("#110 spectral_corr (decisive: with the old spectral flag "
                    "the verdict would be %s%s)"
                    % ("PASS" if cf_ok else "FAIL",
                       ", even with the #95-corrected rms flag"
                       if rms_moved else ""))
        if rms_moved:
            return "#95 rms-flag correction (the spectral leg is not decisive)"
    classes = {c["class"] for c in changes}
    spec = "BUDGET-#110" in classes or any(
        c["class"] == "VERDICT" and "beyond_model_error" in c["key"]
        for c in changes)
    rms = "RMS-FLAG-#95" in classes
    rer = "RE-RENDER" in classes
    sch = "SCHEMA-#100" in classes
    sch111 = "SCHEMA-#111" in classes
    causes = [n for f, n in ((spec, "#110 spectral_corr"),
                             (rms, "#95 rms-flag correction"),
                             (rer, "control re-render"),
                             (sch, "#100 tail gate"),
                             (sch111, "#111 tail-shape leg")) if f]
    return " + ".join(causes) or "UNATTRIBUTED"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--base-rev", default=None,
                    help="revision to attribute against (default: the merge "
                         "base of HEAD with --main-ref)")
    ap.add_argument("--main-ref", default=MAIN_REF)
    ap.add_argument("--out-dir", default=os.path.join(
        REPO, "reports", "spectral-corr-fs-floor", "artifacts"))
    args = ap.parse_args()
    args.base_rev = resolve_base_rev(args.base_rev, args.main_ref)

    lines = []

    def emit(s=""):
        lines.append(s)
        print(s)

    emit("Issue #110 regrade ledger: committed artifacts at base %s (main as "
         "this branch last merged it) vs working tree" % args.base_rev[:12])
    emit("definition: tools/compare_audio_reference.py SPECTRAL_CORR_* "
         "(fs-log-floor-v2, -100 dBFS/bin)")
    emit("")
    changed = set(subprocess.run(
        ["git", "diff", "--name-only", args.base_rev, "--", "reports"],
        cwd=REPO, capture_output=True, text=True).stdout.split())
    regenerated, flips, untouched, unexplained = [], [], [], []
    for p in sorted(glob.glob(os.path.join(REPO, "reports", "**", "*.json"),
                              recursive=True)):
        rel = os.path.relpath(p, REPO)
        if rel.startswith("reports/spectral-corr-fs-floor/"):
            continue
        raw = open(p).read()
        if "spectral_corr" not in raw and rel not in changed:
            continue
        new = json.loads(raw)
        old_src = git_show(args.base_rev, rel) if rel in changed else raw
        if old_src is None:
            # added by this branch: there is no base record to attribute
            # against, so it cannot be silently skipped either
            unexplained.append((rel, "/", "<absent at base>", "ADDED"))
            continue
        old = json.loads(old_src)
        if not (has_spectral_value(old) or has_spectral_value(new)
                or rel in changed):
            continue
        lo, ln = leaves(old), leaves(new)
        changes = []
        for k in sorted(set(lo) | set(ln)):
            a, b = lo.get(k, "<absent>"), ln.get(k, "<absent>")
            if a == b:
                continue
            c = classify(rel, k, a, b, ln)
            if c == "OTHER":
                unexplained.append((rel, k, a, b))
            changes.append({"key": k, "class": c, "old": a, "new": b})
        if changes:
            art_flips = []
            for c in changes:
                if c["class"] == "VERDICT" and c["old"] != "<absent>" and \
                        status_of(c["old"]) != status_of(c["new"]) and \
                        "beyond_model_error_via" not in c["key"]:
                    art_flips.append({"artifact": rel, "key": c["key"],
                                      "old": status_of(c["old"]),
                                      "new": status_of(c["new"])})
            cause = cause_of_flip(changes, lo, ln)
            for f in art_flips:
                f["cause"] = cause
            flips.extend(art_flips)
            counts = {}
            for c in changes:
                counts[c["class"]] = counts.get(c["class"], 0) + 1
            regenerated.append({"artifact": rel, "class_counts": counts,
                                "verdict_flips": art_flips,
                                "changes": changes})
        elif has_spectral_value(new):
            why = next((w for pat, w in NOT_MIGRATED if re.search(pat, rel)),
                       "UNTOUCHED: graded by a migrated comparator but NOT "
                       "regenerated -- must be explained in EVIDENCE.md")
            untouched.append({"artifact": rel, "reason": why})

    for rel in sorted(changed):
        if rel.endswith(".json") and not rel.startswith(
                "reports/spectral-corr-fs-floor/") and \
                not os.path.exists(os.path.join(REPO, rel)):
            unexplained.append((rel, "/", "present at base", "DELETED"))

    emit("REGENERATED (%d artifacts)" % len(regenerated))
    for r in regenerated:
        emit("  %s   [%s]" % (r["artifact"], ", ".join(
            "%s=%d" % kv for kv in sorted(r["class_counts"].items()))))
        for c in r["changes"]:
            if c["class"] == "SPECTRAL":
                emit("      %-13s %-52s %s -> %s"
                     % (c["class"], c["key"][-52:],
                        "%.6f" % c["old"] if isinstance(c["old"], float)
                        else c["old"],
                        "%.6f" % c["new"] if isinstance(c["new"], float)
                        else c["new"]))
            elif c["class"] in ("BUDGET-#110", "VERDICT", "RMS-FLAG-#95",
                                "OTHER"):
                emit("      %-13s %-52s %s -> %s"
                     % (c["class"], c["key"][-52:], str(c["old"])[:48],
                        str(c["new"])[:48]))
    emit("")
    emit("VERDICT / CONTROL-STATUS FLIPS (%d)" % len(flips))
    for f in flips:
        emit("  %s %s: %s -> %s   [cause: %s]"
             % (f["artifact"], f["key"], f["old"], f["new"], f["cause"]))
    emit("")
    emit("CARRY spectral_corr BUT NOT REGENERATED (%d)" % len(untouched))
    for u in untouched:
        emit("  %s -- %s" % (u["artifact"], u["reason"]))
    emit("")
    emit("UNEXPLAINED diffs: %d" % len(unexplained))
    for u in unexplained:
        emit("  %s %s: %r -> %r" % u)

    os.makedirs(args.out_dir, exist_ok=True)
    with open(os.path.join(args.out_dir, "regrade-ledger.txt"), "w") as f:
        f.write("\n".join(lines) + "\n")
    with open(os.path.join(args.out_dir, "regrade-ledger.json"), "w") as f:
        json.dump({"issue": 110, "base_rev": args.base_rev,
                   "regenerated": regenerated, "verdict_flips": flips,
                   "not_regenerated": untouched,
                   "unexplained": [list(u) for u in unexplained]},
                  f, indent=2)
        f.write("\n")
    return 1 if unexplained else 0


if __name__ == "__main__":
    sys.exit(main())
